//go:build windows

package junkclean

import "winfix/internal/core"

// Tool описывает утилиту для главного меню и командной строки.
func Tool() core.Tool {
	return core.Tool{
		Name:    "junk",
		Aliases: []string{"junkclean", "clean"},
		Title:   "Очистка мусора",
		Summary: "Находит и удаляет временные файлы, кэши браузеров и приложений, дампы сбоев, старые логи и корзину. Сначала показывает, сколько места займёт каждая категория.",
		Details: `Работает только по белому списку путей: документы, загрузки, куки и пароли не затрагиваются.
Файлы, занятые другими программами, пропускаются без ошибок.
Категории «по желанию» (кэши разработчика, шейдер-кэш, DISM) по умолчанию не выбираются.`,
		Commands: []core.Command{
			{Name: "scan", Title: "Только посмотреть, сколько мусора",
				Hint: "Сканирует диск и показывает таблицу категорий с размерами. Ничего не удаляет, права администратора не нужны.",
				Run:  func(args []string) { run(append([]string{"--scan"}, args...)) }},
			{Name: "clean", Title: "Найти и очистить",
				Hint:  "Показывает таблицу категорий, вы выбираете номера (1,3,5-7 / a — рекомендуемые / all — все) и подтверждаете удаление. Лучше от администратора: тогда чистятся и системные папки.",
				Usage: "--yes — без вопросов, только рекомендуемые; --all — вместе с --yes и «по желанию»; --scan — только показать; --no-elevate — не просить права",
				Run:   run},
		},
	}
}
