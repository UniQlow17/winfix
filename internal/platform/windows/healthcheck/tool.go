//go:build windows

package healthcheck

import "winfix/internal/core"

// Tool описывает утилиту для главного меню и командной строки.
func Tool() core.Tool {
	return core.Tool{
		Name:    "health",
		Aliases: []string{"healthcheck", "check"},
		Title:   "Проверка здоровья компьютера (общий отчёт)",
		Summary: "Начните с неё: за 30–60 секунд соберёт картину состояния ПК (диски, память, сбои, безопасность, драйверы) и подскажет, какой утилитой что исправлять. Ничего не меняет.",
		Details: `Собирает данные о системе, дисках, событиях за 7 дней, безопасности, устройствах и автозагрузке.
Выводит цветной отчёт ([ OK ] хорошо, [ !! ] предупреждение, [FAIL] требует внимания)
и в конце перечисляет утилиты WinFix, которые стоит запустить.
Отчёт сохраняется в папку отчётов (меню → «Открыть папку отчётов»).`,
		Commands: []core.Command{
			{Name: "run", Title: "Проверить компьютер",
				Hint:  "Полный отчёт о состоянии ПК с рекомендациями. Только чтение.",
				Usage: "--no-save — не сохранять отчёт в файл",
				Run:   run},
		},
	}
}
